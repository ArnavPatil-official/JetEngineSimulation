def tree_manifest(folder):
    """sha256/size of every regular file; any symlink under the tree is rejected."""
    folder = Path(folder)
    need(folder.is_dir() and not folder.is_symlink(), f"Missing or symlinked tree: {folder}")
    result = {}
    for directory, dirs, files in os.walk(folder, followlinks=False):
        for name in (*dirs, *files):
            need(not os.path.islink(os.path.join(directory, name)), f"Symlink in consumed tree: {name}")
        for name in files:
            path = Path(directory) / name
            result[path.relative_to(folder).as_posix()] = {"sha256": sha256(path), "size": path.stat().st_size}
    return result


def verify_unchanged(folder, manifest, *, exact):
    """Original bytes and names survive; ``exact`` also forbids any added file."""
    current = tree_manifest(folder)
    missing = sorted(set(manifest) - set(current))
    changed = sorted(name for name in manifest if name in current and current[name] != manifest[name])
    added = sorted(set(current) - set(manifest))
    need(not missing and not changed, f"Consumed files changed or vanished: {(missing + changed)[:5]}")
    need(not (exact and added), f"Unexpected files added to the consumed tree: {added[:5]}")
    return {"files": len(manifest), "added": added}


def active_owner_processes(proc="/proc", *, own_pid=None):
    """Other live pipeline/recovery interpreters; argv-based so a shell that merely names the script is ignored."""
    own_pid = os.getpid() if own_pid is None else own_pid
    found = []
    proc = Path(proc)
    if not proc.is_dir():
        return found
    for entry in proc.iterdir():
        if not entry.name.isdigit() or int(entry.name) == own_pid:
            continue
        try:
            argv = (entry / "cmdline").read_bytes().split(b"\0")
        except OSError:
            continue
        argv = [part.decode(errors="replace") for part in argv if part]
        if argv and Path(argv[0]).name.startswith("python") and any(
                Path(part).name in OWNER_CMDLINES for part in argv[1:3]):
            found.append(int(entry.name))
    return found


def verify_sources(old_sources, new_sources, *, old_bytes, edits=AUTHORIZED_EDITS, self_path=SELF_PATH):
    """Only the reviewed fix (exact content) and this additive script may differ from the original snapshot."""
    added = sorted(set(new_sources) - set(old_sources))
    removed = sorted(set(old_sources) - set(new_sources))
    changed = sorted(name for name in old_sources if name in new_sources and old_sources[name] != new_sources[name])
    need(added == [self_path], f"Source additions other than the recovery script: {added}")
    need(not removed, f"Source files removed since the original snapshot: {removed}")
    need(changed == sorted(edits), f"Unauthorized source drift: {changed}")
    for name, replacements in edits.items():
        original = old_bytes(name)
        need(sha256_bytes(original) == old_sources[name], f"Source commit content differs from the recorded snapshot: {name}")
        expected = original
        for before, after in replacements:
            need(expected.count(before.encode()) == 1, f"Authorized edit anchor is not unique: {name}")
            expected = expected.replace(before.encode(), after.encode())
        need(sha256_bytes(expected) == new_sources[name], f"{name} is not exactly the authorized serialization fix")
    return {"added": added, "changed": changed, "removed": removed,
            "mapping": {name: {"original_sha256": old_sources[name], "current_sha256": new_sources[name]} for name in changed},
            "original_sources_sha256": fingerprint(old_sources), "current_sources_sha256": fingerprint(new_sources)}


def checked_git(root, *args):
    result = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True)
    if result.returncode:
        raise RecoveryError(f"git {' '.join(args[:2])} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def git_blob(root, commit, path):
    result = subprocess.run(["git", "show", f"{commit}:{path}"], cwd=root, capture_output=True)
    need(result.returncode == 0, f"Source commit does not contain {path}")
    return result.stdout


def verify_git(root, *, git=checked_git, source_commit=SOURCE_COMMIT, branch=BRANCH, allowed=ALLOWED_CHANGES):
    """Known source commit; every change since it is on the exact authorized file list."""
    need(git(root, "cat-file", "-t", source_commit) == "commit", "Known source commit is absent")
    head = git(root, "rev-parse", "HEAD")
    try:
        git(root, "merge-base", "--is-ancestor", source_commit, "HEAD")
    except RecoveryError:
        raise RecoveryError("HEAD does not descend from the known source commit") from None
    changed = set(git(root, "diff", "--name-only", source_commit).splitlines())
    untracked = {name for name in git(root, "ls-files", "--others", "--exclude-standard").splitlines()
                 if not name.startswith("outputs/")}
    unauthorized = sorted((changed | untracked) - set(allowed))
    need(not unauthorized, f"Changes outside the authorized file list: {unauthorized[:8]}")
    blockers = []
    if git(root, "branch", "--show-current") != branch:
        blockers.append(f"not on branch {branch}")
    if git(root, "status", "--porcelain", "--untracked-files=no"):
        blockers.append("tracked changes are uncommitted; commit the authorized files first")
    if git(root, "diff", "--cached", "--name-only"):
        blockers.append("staged files present (publication refuses them)")
    return {"head": head, "source_commit": source_commit, "changed_since_source": sorted(changed),
            "untracked_outside_outputs": sorted(untracked), "run_blockers": blockers}


def _owned(root, name):
    relative = Path(name)
    need(not relative.is_absolute() and ".." not in relative.parts, f"Escaped path: {name}")
    path = root / relative
    need(not path.is_symlink() and path.resolve().is_relative_to(root) and path.is_file(), f"Missing/symlinked/escaped file: {name}")
    return path


def verify_sealed_score(layout, pins, verify_artifacts):
    """Pinned score artifacts, reservation targets, frozen predictions/weights and bound original identity."""
    root, saf, old = layout.root, layout.saf, layout.old
    # Immutable pins and the reservation.
    pinned = {}
    for name, expected in pins.items():
        need(sha256(_owned(root, layout.relative(saf / name))) == expected, f"Pinned artifact changed: {name}")
        pinned[name] = expected
    reservation = read_json(saf / "score_reservation.json")
    reg_sha = sha256(root / SAF_REGISTRATION)
    need(reservation["registration_sha256"] == reg_sha, "Reservation registration differs")
    need(reservation["predictions_freeze_sha256"] == pins["predictions_freeze.json"]
         and reservation["selection_sha256"] == pins["selection.json"], "Reservation does not bind the pinned freeze/selection")
    expected_targets = {layout.relative(saf / name) for name in SEALED_TARGETS} | set(layout.registration["sole_score"]["named_paths"])
    need(set(reservation["targets"]) == expected_targets, "Reservation target set differs from the registered targets")
    for name, expected in reservation["targets"].items():
        need(sha256(_owned(root, name)) == expected, f"Reservation target changed: {name}")
    frozen = read_json(saf / "predictions_freeze.json")
    need(len(frozen["predictions"]) == 72 and len(frozen["weights"]) == 24, "Frozen prediction/weight counts differ")
    for key in ("predictions", "weights", "inputs"):
        verify_artifacts(saf, frozen[key])
    need(frozen["selection_sha256"] == pins["selection.json"] and frozen["registration_sha256"] == reg_sha
         and frozen["validation_sha256"] == sha256(saf / "validation.json"), "Prediction freeze bindings changed")
    # Identity: reservation, f reservation and the completed d/e producers all agree and match the source snapshot.
    identity = reservation["identity"]
    old_sources = read_json(old / "scientific_sources.json")
    need(identity["git_head"] == SOURCE_COMMIT and identity["registration_sha256"] == reg_sha, "Foreign original identity")
    need(read_json(old / "runs/f/reservation.json")["identity"] == identity, "Original f lease identity differs")
    for letter in "de":
        need(read_json(old / f"runs/{letter}/terminal.json")["identity"] == identity, f"Original {letter} producer identity differs")
    simulator = identity["simulator"]
    need(fingerprint(simulator) == identity["simulator_identity_sha256"] and simulator["source_hashes"] == old_sources
         and identity["source_hashes"] == old_sources, "Original identity does not match the recorded source snapshot")
    for name in ("generation_terminal.json", "product.json"):
        need(read_json(saf / name).get("simulator_identity_sha256") == identity["simulator_identity_sha256"],
             f"{name} was produced by another simulator identity")
    return {"pinned": pinned, "reservation": reservation, "identity": identity, "old_sources": old_sources,
            "registration_sha256": reg_sha}


