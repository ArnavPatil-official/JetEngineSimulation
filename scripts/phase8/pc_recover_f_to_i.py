def first_recovery_terminal(first):
    """The single terminal summary of the first recovery: the known ERROR at stage g after a and f."""
    terminals = sorted((first / "terminals").glob("*.json"))
    need(len(terminals) == 1, "The first recovery must hold exactly one terminal summary")
    summary = read_json(terminals[0])
    need(summary.get("status") == "ERROR" and summary.get("stopped_at") == "g" and summary.get("error") == KNOWN_G_ERROR,
         "The first recovery did not end with the known nozzle ERROR at stage g")
    need([entry["stage"] for entry in summary.get("stages", [])] == ["a", "f"], "The first recovery completed stages other than a and f")
    return terminals[0], summary


def verify_nozzle(root, nozzle):
    """Sealed failed nozzle attempt: every recorded hash intact; only the coverage receipt is absent."""
    root, nozzle = Path(root), Path(nozzle)
    rel = nozzle.relative_to(root).as_posix()
    manifest = tree_manifest(nozzle)
    terminal = read_json(nozzle / "terminal.json")
    need(terminal.get("status") == "FAIL" and terminal.get("scientific_verdict") == "FAIL"
         and terminal.get("execution_complete") is False and terminal.get("outputs_complete") is False
         and terminal.get("errors") == [], "Nozzle terminal differs from the known FAIL/INCOMPLETE state")
    missing = sorted(name for name in terminal["expected_outputs"] if not (root / name).exists())
    need(missing == [f"{rel}/{MISSING_NOZZLE_OUTPUT}"], f"Nozzle outputs missing other than the known coverage file: {missing}")
    for name, expected in {**terminal["artifact_hashes"], **read_json(nozzle / "hashes.json")}.items():
        need(sha256(_owned(root, name)) == expected, f"Nozzle artifact changed: {name}")
    reservation = read_json(nozzle / "score_reservation.json")
    need(len(reservation["checkpoint_hashes"]) == 6, "Nozzle score reservation does not bind six frozen fits")
    for name, expected in reservation["checkpoint_hashes"].items():
        need(sha256(_owned(root, name)) == expected, f"Nozzle frozen fit changed: {name}")
    need(reservation["input_manifest_sha256"] == sha256(nozzle / "input_manifest.json"), "Nozzle input manifest binding changed")
    report = read_json(nozzle / "report.json")
    need(report.get("status") == "FAIL" and report.get("registered_status") is not None, "Nozzle report is not the recorded FAIL")
    return {"manifest": manifest, "terminal": {key: terminal[key] for key in ("status", "scientific_verdict", "execution_complete",
            "outputs_complete", "errors", "wall_s")}, "missing_outputs": missing, "frozen_fits": 6,
            "report_status": report["status"], "registered_status": report["registered_status"]}


