def prepare_metadata(layout, original, bridge, git_info, config, new_sources):
    """Consumed marker first, then config, carried originals and the recovery record (all exclusive writes)."""
    from scripts.phase8.pc_runtime import write_once
    new = layout.new
    new.mkdir(parents=True, exist_ok=False)
    write_once(new / "recovery/consumed.json", {"schema": "pc-recovery-consumed-v1", "created_utc": utc(),
        "pid": os.getpid(), "argv": list(sys.argv), "source_commit": SOURCE_COMMIT, "head": git_info["head"]})
    write_once(new / "config.json", config.record())
    from scripts.pc_pipeline import describe as pipeline_describe
    write_once(new / "plan.json", pipeline_describe(config))
    copy_exact(layout.old / "parity20.json", new / "parity20.json")
    carried = {}
    for letter in CARRIED:
        carried[f"checkpoints/{letter}.json"] = copy_exact(layout.old / f"checkpoints/{letter}.json",
                                                           new / f"checkpoints/{letter}.json")
    for letter in "de":
        for name in ("reservation.json", "terminal.json", "released_lease.json"):
            carried[f"runs/{letter}/{name}"] = copy_exact(layout.old / f"runs/{letter}/{name}", new / f"runs/{letter}/{name}")
    evidence = {}
    for name in ("checkpoints/f.started.json", "runs/f/reservation.json", "runs/f/terminal.json", "runs/f/released_lease.json"):
        evidence[name] = copy_exact(layout.old / name, new / "recovery/original_f_attempt" / name.replace("/", "__"))
    for path in sorted((layout.old / "terminals").glob("*.json")):
        evidence[f"terminals/{path.name}"] = copy_exact(path, new / "recovery/original_f_attempt" / f"terminals__{path.name}")
    write_once(new / "recovery/original_metadata_manifest.json", original["old_manifest"])
    write_once(new / "recovery/preexisting_saf_manifest.json", original["saf_manifest"])
    record = {"schema": "pc-recovery-record-v1", "created_utc": utc(), "source_commit": SOURCE_COMMIT, "head": git_info["head"],
        "branch": BRANCH, "reason": "Stage f TypeError: Object of type bool is not JSON serializable (numpy.bool_ in named_metrics.json)",
        "authorization": "docs/plan.md exact user-approved recovery block 2026-10-05; reviewed operational clarification of the "
                         "registration's sole_score.crash_recovery exact-resume clause; the registration is not amended",
        "original_config_sha256": original["config_sha256"], "new_config_sha256": fingerprint(config.record()),
        "pinned_artifacts": original["pinned"], "original_identity": original["identity"],
        "source_mapping": {**bridge, "authorized_edits": {name: [[a, b] for a, b in edits] for name, edits in AUTHORIZED_EDITS.items()},
                           "script_sha256": new_sources[SELF_PATH]},
        "operational_mapping": "Generated data/producer proofs (stages d, e) keep the original python-v6 simulator identity and are "
                               "verified against it; stages f, g, h run under the live identity of the current sources, which are verified "
                               "against the original snapshot to differ only by the reviewed serialization fix and this script.",
        "carried_original_files_sha256": carried, "original_f_attempt_evidence_sha256": evidence,
        "carried_stages": list(CARRIED), "new_stages": list(NEW_STAGES),
        "original_f_attempt_seconds": original["original_f_attempt_seconds"]}
    write_once(new / "recovery/recovery_record.json", record)
    return record


def run_recovery(root, *, workflow_class=None, publish=None, new_sources=None, old_bytes=None, git=checked_git,
                 sleep_inhibitor=None, pins=None):
    """Verify, arm the one-attempt marker, then execute a, f, g, h, i once. Never retried."""
    from scripts.pc_pipeline import Config, publish_outputs, validate_checkpoint
    from scripts.phase8.pc_runtime import write_once
    from simulation.runtime import SleepInhibitor
    layout, original, bridge, git_info, current = verify_all(
        root, new_sources=new_sources, old_bytes=old_bytes, git=git, pins=pins)
    need(not git_info["run_blockers"], "Run blocked: " + "; ".join(git_info["run_blockers"]))
    for key in THREAD_ENV:
        need(os.environ.get(key) == "1", f"{key}=1 is required")
    config = Config(root=layout.root, workers=10, backend="torch", device="cpu", metadata_dir=Path(NEW_METADATA))
    new_sha = fingerprint(config.record())
    prepare_metadata(layout, original, bridge, git_info, config, current)
    os.environ["CATJET_SIMULATOR_BACKEND"] = "python"
    summary = {"status": "RUNNING", "started_utc": utc(), "recovery": True, "stages": [], "a2": "DEFERRED"}
    checkpoints = layout.new / "checkpoints"
    owner = {"owner_pid": os.getpid(), "config_sha256": new_sha, "started_utc": utc(), "argv": list(sys.argv)}
    write_once(layout.new / "owner.json", owner)
    active, completed = None, {letter: read_json(checkpoints / f"{letter}.json") for letter in CARRIED}
    try:
        workflow = (workflow_class or make_workflow_class())(layout.root, layout.new, original=original, bridge=bridge,
            current_sources=current, workers=config.workers, backend=config.backend, device=config.device)
        handlers = {letter: getattr(workflow, letter) for letter in "afgh"}
        handlers["i"] = (lambda: publish_outputs(config)) if publish is None else publish
        with (sleep_inhibitor or SleepInhibitor)() as inhibitor:
            summary["sleep_inhibition"] = inhibitor.metadata
            for letter in NEW_STAGES:
                active = letter
                for prior, receipt in completed.items():
                    validate_checkpoint(layout.root, receipt, original["config_sha256"] if prior in CARRIED else new_sha)
                started, before = utc(), time.perf_counter()
                write_once(checkpoints / f"{letter}.started.json", {"stage": letter, "started_utc": started, "owner": owner})
                result = handlers[letter]()
                if not isinstance(result, dict) or result.get("status") != "COMPLETE" or result.get("execution_complete") is not True:
                    raise RuntimeError(f"Stage {letter} did not complete: {result}")
                elapsed = time.perf_counter() - before
                receipt = {**result, "stage": letter, "status": "COMPLETE", "config_sha256": new_sha,
                           "started_utc": started, "finished_utc": utc(), "elapsed_seconds": elapsed}
                if letter == "f":
                    # Stage h charges the actually incurred f cost: the consumed first attempt plus this resume.
                    receipt.update(elapsed_seconds=elapsed + original["original_f_attempt_seconds"],
                                   recovery_elapsed_seconds=elapsed,
                                   original_attempt_elapsed_seconds=original["original_f_attempt_seconds"])
                validate_checkpoint(layout.root, receipt, new_sha)
                write_once(checkpoints / f"{letter}.json", receipt)
                completed[letter] = receipt
                summary["stages"].append({"stage": letter, "scientific_verdict": receipt.get("scientific_verdict")})
                if letter == "f":
                    verify_unchanged(layout.old, original["old_manifest"], exact=True)
                    verify_unchanged(layout.saf, original["saf_manifest"], exact=False)
            verdicts = {r.get("scientific_verdict") for r in completed.values()}
            summary.update(status="COMPLETE", scientific_verdict="FAIL" if "FAIL" in verdicts else
                           "INCOMPLETE" if verdicts & {"BLOCKED", "INCOMPLETE"} else "PASS")
        verify_unchanged(layout.old, original["old_manifest"], exact=True)
        verify_unchanged(layout.saf, original["saf_manifest"], exact=False)
    except BaseException as exc:
        summary.update(status="ERROR", stopped_at=active, error=f"{type(exc).__name__}: {exc}", traceback=traceback.format_exc())
    finally:
        summary["finished_utc"] = utc()
        write_once(layout.new / "terminals" / (uuid.uuid4().hex + ".json"), summary)
        if (layout.new / "owner.json").exists() and read_json(layout.new / "owner.json") == owner:
            (layout.new / "owner.json").unlink()
    summary["recovery_record_sha256"] = sha256(layout.new / "recovery/recovery_record.json")
    return summary


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="verify only (default); writes nothing")
    mode.add_argument("--run", action="store_true", help="execute the one-shot recovery")
    args = parser.parse_args(argv)
    try:
        if args.run:
            result = run_recovery(ROOT)
            print(json.dumps(result, indent=2, allow_nan=False))
            return 0 if result["status"] == "COMPLETE" else 1
        layout, original, bridge, git_info, _ = verify_all(ROOT)
        print(json.dumps(describe(layout, original, bridge, git_info), indent=2, allow_nan=False))
        return 0
    except Exception as exc:
        print(json.dumps({"status": "ERROR", "error": f"{type(exc).__name__}: {exc}"}, indent=2), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
