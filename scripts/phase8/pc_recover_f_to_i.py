class ExactResume:
    """Writer adapter for score_all: existing files must match regenerated bytes; new files are held until all do."""

    def __init__(self, saf):
        self.saf = Path(saf).resolve()
        self.compared, self.pending = {}, {}

    def write(self, path, value):
        from scripts.phase8.saf_surrogate.registration import json_bytes
        data = value if isinstance(value, bytes) else json_bytes(value)
        path = Path(path)
        need(not path.is_symlink(), f"Symlinked score output: {path}")
        key = path.resolve()
        need(self.saf in key.parents, f"Score output escapes the SAF attempt: {path}")
        need(key not in self.compared and key not in self.pending, f"Score output written twice: {path.name}")
        if key.exists():
            need(key.is_file() and key.read_bytes() == data, f"Regenerated bytes differ from the existing {key.name}")
            self.compared[key] = sha256_bytes(data)
        else:
            self.pending[key] = data
        return sha256_bytes(data)

    @contextlib.contextmanager
    def patched(self):
        from scripts.phase8.saf_surrogate import run as saf_run, score
        saved = (score.write_once, saf_run.write_once)
        score.write_once = saf_run.write_once = self.write
        try:
            yield self
        finally:
            score.write_once, saf_run.write_once = saved

    def commit(self):
        """Create only the never-written outputs, exclusively (xb); nothing existing can be replaced."""
        from scripts.phase8.saf_surrogate.registration import write_once
        for key, data in sorted(self.pending.items()):
            write_once(key, data)
        return {"byte_identical": sorted(self.relative(k) for k in self.compared),
                "created": sorted(self.relative(k) for k in self.pending)}

    def relative(self, key):
        return key.relative_to(self.saf).as_posix()


class OriginalIdentity:
    """The original bound identity; score_all reads only these two attributes to rebuild the reservation."""

    def __init__(self, identity, binary_sha256):
        self.identity, self.binary_sha256 = copy.deepcopy(identity), binary_sha256


class OriginalDataView:
    """Live context that answers generated-data identity questions with the original simulator identity.

    Everything else (root, lease, workers, source integrity) is the live current context. Used only to read
    the unchanged d/e producer proofs; the proofs themselves are still fully verified by the existing code.
    """

    def __init__(self, context, simulator, simulator_sha256):
        self._context = context
        self.simulator_identity, self.simulator_identity_sha256 = simulator, simulator_sha256

    def __getattr__(self, name):
        return getattr(self._context, name)


@contextlib.contextmanager
def bridged_command_specs(bridge, current_sources):
    """Child-process specs carry the original manifest sources; map only the authorized edit to its current hash."""
    from scripts.phase8.saf_surrogate import run as saf_run
    original = saf_run.command_spec

    def command_spec(*args, **kwargs):
        spec = original(*args, **kwargs)
        mapped = dict(spec["source_hashes"])
        for name in bridge["changed"]:
            if name in mapped:
                mapped[name] = current_sources[name]
        spec["source_hashes"] = mapped
        spec["operational_source_bridge"] = {key: bridge[key] for key in
                                              ("original_sources_sha256", "current_sources_sha256", "changed")}
        return spec

    saf_run.command_spec = command_spec
    try:
        yield
    finally:
        saf_run.command_spec = original


def copy_exact(source, destination):
    from scripts.phase8.pc_runtime import write_once
    data = Path(source).read_bytes()
    write_once(destination, data)
    need(sha256(destination) == sha256_bytes(data), f"Copy differs from the original: {source}")
    return sha256_bytes(data)


def make_workflow_class():
    from scripts.phase8 import python_pc
    from scripts.phase8.pc_runtime import write_once

    class RecoveryWorkflow(python_pc.ScientificWorkflow):
        def __init__(self, root, metadata, *, original, bridge, current_sources, **kwargs):
            super().__init__(root, metadata, **kwargs)
            self.original, self.bridge, self.current_sources = original, bridge, current_sources

        def f(self):
            from scripts.phase8.saf_surrogate.score import score_all
            context, run = self.owned("f", python_pc.REGISTRATIONS["saf"])
            try:
                bound = OriginalIdentity(self.original["identity"], self.original["reservation"]["binary_sha256"])
                resume = ExactResume(self.saf)
                with resume.patched():
                    scored = score_all(self.root, self.saf, self.reg["saf"], context.identity["registration_sha256"],
                                       bound, run, backend=self.backend)
                outcome = resume.commit()
                write_once(self.saf / "sole_score_summary.json", scored)
                verdict = "PASS" if all(scored[k] for k in ("fidelity_pass", "ranking_pass", "precision_pass")) else "FAIL"
                return self.finish(run, [self.saf], scientific_verdict=verdict, extra={"score_resume": outcome})
            except BaseException as exc:
                if not run._released:
                    run.release({"status": "ERROR", "exit_code": 1, "errors": [str(exc)], "outputs_complete": False})
                raise

        def g(self):
            from scripts.phase8.nozzle_ode import run as nozzle
            original = self.original["identity"]

            def source_loader(root, reg, context, out):
                view = OriginalDataView(context, original["simulator"], original["simulator_identity_sha256"])
                return python_pc.load_source_properties(root, reg, view, out)

            nozzle.run(self.root, context_factory=self.context_factory, source_loader=source_loader,
                       portable=True, backend=self.backend)
            terminal = python_pc.read_json(self.nozzle / "terminal.json")
            if terminal["status"] == "ERROR" or terminal.get("execution_complete") is not True \
                    or terminal.get("outputs_complete") is not True:
                raise RuntimeError("Nozzle execution did not complete: " + terminal["status"])
            return {"status": "COMPLETE", "execution_complete": True, "scientific_verdict": terminal["status"],
                    "artifacts": python_pc.artifacts(self.root, self.nozzle)}

        def h(self):
            with bridged_command_specs(self.bridge, self.current_sources):
                return super().h()

    return RecoveryWorkflow


