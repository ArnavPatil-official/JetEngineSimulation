def verify_retained(v, *, saf_exact):
    """Original, first-recovery and nozzle trees stay byte-identical; the SAF tree only gains legitimate h outputs."""
    layout = v["layout"]
    verify_unchanged(layout.old, v["old_manifest"], exact=True)
    verify_unchanged(layout.new, v["first_manifest"], exact=True)
    from scripts.pc_pipeline import scientific_outputs
    nozzle = scientific_outputs(layout.root)["nozzle"]
    verify_unchanged(nozzle, v["nozzle"]["manifest"], exact=True)
    need(not (nozzle / MISSING_NOZZLE_OUTPUT).exists(), "The absent nozzle coverage receipt must stay absent")
    return verify_unchanged(layout.saf, v["saf_manifest"], exact=saf_exact)


def run_timing_publish(root, *, workflow_class=None, publish=None, new_sources=None, old_bytes=None, blob=None, git=checked_git,
                       sleep_inhibitor=None, pins=None):
    """Verify, arm the one-attempt marker, then run only h and i once (preceded by the stage-a source snapshot)."""
    from scripts.pc_pipeline import Config, publish_outputs, validate_checkpoint
    from scripts.phase8.pc_runtime import write_once
    from simulation.runtime import SleepInhibitor
    v = verify_continuation(root, new_sources=new_sources, old_bytes=old_bytes, blob=blob, git=git, pins=pins)
    layout, timing, git_info = v["layout"], v["timing"], v["git"]
    need(not git_info["run_blockers"], "Run blocked: " + "; ".join(git_info["run_blockers"]))
    for key in THREAD_ENV:
        need(os.environ.get(key) == "1", f"{key}=1 is required")
    config = Config(root=layout.root, workers=10, backend="torch", device="cpu", metadata_dir=Path(TIMING_METADATA))
    new_sha = fingerprint(config.record())
    prepare_continuation_metadata(v, config, git_info, v["new_sources"])
    os.environ["CATJET_SIMULATOR_BACKEND"] = "python"
    summary = {"status": "RUNNING", "started_utc": utc(), "continuation": "timing-publish-only", "stages": [], "a2": "DEFERRED"}
    checkpoints = timing / "checkpoints"
    owner = {"owner_pid": os.getpid(), "config_sha256": new_sha, "started_utc": utc(), "argv": list(sys.argv)}
    write_once(timing / "owner.json", owner)
    shas = {**{letter: v["old_config_sha256"] for letter in CARRIED}, "f": v["first_config_sha256"]}
    completed, active = {letter: read_json(checkpoints / f"{letter}.json") for letter in (*CARRIED, "f")}, None
    try:
        workflow = (workflow_class or make_workflow_class())(layout.root, timing, original=v["sealed"], bridge=v["bridge"],
            current_sources=v["new_sources"], workers=config.workers, backend=config.backend, device=config.device)
        handlers = {"a": workflow.a, "h": workflow.h, "i": (lambda: publish_outputs(config)) if publish is None else publish}
        with (sleep_inhibitor or SleepInhibitor)() as inhibitor:
            summary["sleep_inhibition"] = inhibitor.metadata
            verify_retained(v, saf_exact=True)
            for letter in "a" + TIMING_STAGES:
                active = letter
                for prior, receipt in completed.items():
                    validate_checkpoint(layout.root, receipt, shas.get(prior, new_sha))
                check_cost_only_g(read_json(checkpoints / "g.json"))
                started, before = utc(), time.perf_counter()
                write_once(checkpoints / f"{letter}.started.json", {"stage": letter, "started_utc": started, "owner": owner})
                result = handlers[letter]()
                if not isinstance(result, dict) or result.get("status") != "COMPLETE" or result.get("execution_complete") is not True:
                    raise RuntimeError(f"Stage {letter} did not complete: {result}")
                receipt = {**result, "stage": letter, "status": "COMPLETE", "config_sha256": new_sha, "started_utc": started,
                           "finished_utc": utc(), "elapsed_seconds": time.perf_counter() - before}
                validate_checkpoint(layout.root, receipt, new_sha)
                write_once(checkpoints / f"{letter}.json", receipt)
                completed[letter] = receipt
                shas[letter] = new_sha
                summary["stages"].append({"stage": letter, "scientific_verdict": receipt.get("scientific_verdict")})
                if letter != "i":
                    verify_retained(v, saf_exact=letter == "a")
            summary["saf_files_added"] = verify_retained(v, saf_exact=False)["added"]
            summary.update(status="COMPLETE", publication={key: completed["i"].get(key) for key in ("branch", "commit")})
        # Carried results are reported regardless of the publication outcome.
        summary["carried"] = {"f": v["first_receipts"]["f"].get("scientific_verdict"),
                              "g": {"status": "INCOMPLETE", "scientific_verdict": "FAIL", "missing_outputs": v["nozzle"]["missing_outputs"]}}
        verdicts = {completed["f"].get("scientific_verdict"), "FAIL", completed["h"].get("scientific_verdict")}
        summary["scientific_verdict"] = "FAIL" if "FAIL" in verdicts else "INCOMPLETE" if verdicts & {"BLOCKED", "INCOMPLETE"} else "PASS"
    except BaseException as exc:
        summary.update(status="ERROR", stopped_at=active, error=f"{type(exc).__name__}: {exc}", traceback=traceback.format_exc())
    finally:
        summary["finished_utc"] = utc()
        write_once(timing / "terminals" / (uuid.uuid4().hex + ".json"), summary)
        if (timing / "owner.json").exists() and read_json(timing / "owner.json") == owner:
            (timing / "owner.json").unlink()
    summary["continuation_record_sha256"] = sha256(timing / "recovery/continuation_record.json")
    return summary


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="verify only (default); writes nothing")
    mode.add_argument("--run", action="store_true", help="execute the one-shot recovery")
    parser.add_argument("--timing-publish-only", action="store_true",
                        help="h/i-only continuation after the recorded nozzle FAIL (never runs f or g); combine with --dry-run or --run")
    args = parser.parse_args(argv)
    try:
        if args.timing_publish_only:
            if args.run:
                result = run_timing_publish(ROOT)
                print(json.dumps(result, indent=2, allow_nan=False))
                return 0 if result["status"] == "COMPLETE" else 1
            print(json.dumps(describe_continuation(verify_continuation(ROOT)), indent=2, allow_nan=False))
            return 0
        if args.run:
            result = run_recovery(ROOT)
            print(json.dumps(result, indent=2, allow_nan=False))
            return 0 if result["status"] == "COMPLETE" else 1
        layout, original, bridge, git_info, _ = verify_all(ROOT)
        print(json.dumps(describe(layout, original, bridge, git_info), indent=2, allow_nan=False))
        return 0
    except Exception as exc:
        print(json.dumps({"status": "ERROR", "error": f"{type(exc).__name__}: {exc}"}, indent=2), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
